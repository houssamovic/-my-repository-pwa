import fs from 'node:fs';
import assert from 'node:assert/strict';
const src = fs.readFileSync(new URL('../functions/api/metadata.js',import.meta.url),'utf8');
const mod = await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const html = '<html><head><title>Other &amp; Default</title><meta property="og:title" content="Repairing a hole in drywall"><meta name="description" content="A useful &amp; practical guide to fixing a hole in the wall"></head></html>';
assert.deepEqual(mod.parseMetadata(html), {title:'Repairing a hole in drywall',description:'A useful & practical guide to fixing a hole in the wall'});
const asReq=url=>({request:new Request(url)});
const reject=await mod.onRequestGet(asReq('https://repo.pages.dev/api/metadata?url=http%3A%2F%2Flocalhost%2F'));
assert.equal(reject.status, 400);
let called=[];
const orig=globalThis.fetch;
globalThis.fetch = async (url,opts)=>{called.push(url);return new Response(html,{status:200,headers:{'content-type':'text/html'}})};
let resp=await mod.onRequestGet(asReq('https://repo.pages.dev/api/metadata?url=https%3A%2F%2Fwww.example.net%2Farticle'));
assert.equal(resp.status,200);
let body=await resp.json(); assert.equal(body.status,'ok');assert.equal(body.title,'Repairing a hole in drywall');assert.equal(called[0],'https://www.example.net/article');
globalThis.fetch=async ()=>new Response('',{status:302,headers:{location:'http://127.0.0.1/private'}});
resp=await mod.onRequestGet(asReq('https://repo.pages.dev/api/metadata?url=https%3A%2F%2Fwww.example.net%2Farticle'));
assert.equal((await resp.json()).status,'unavailable');
globalThis.fetch=async ()=>new Response('x'.repeat(451000),{status:200,headers:{'content-type':'text/html'}});
resp=await mod.onRequestGet(asReq('https://repo.pages.dev/api/metadata?url=https%3A%2F%2Fwww.example.net%2Farticle'));
assert.equal((await resp.json()).status,'unavailable');
globalThis.fetch=orig;
const badMethod=mod.onRequest(); assert.equal(badMethod.status,405);
console.log('PASS 6 metadata tests: parser, URL restrictions, successful fetch, blocked redirect, size cap, method rejection');
